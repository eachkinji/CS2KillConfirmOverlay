"""Generate the shared native UMG curve table from the extracted Anim_Normal JSON.

Run with Python 3; no third party packages required. Textures are lossless atlas crops.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
data = json.loads((HERE / 'normal-animation.json').read_text(encoding='utf-8'))
names = ['CanvasPanel_Root', 'CanvasPanel_Injured', 'MainBG', 'Image_FeedbackIcon',
         'Frame', 'BigFrame', 'SideLinex4', 'Dotx4', 'SideLinex2', 'MainWhite']
num = lambda x: repr(float(x))
fields = []
methods = []

for index, name in enumerate(names):
    w = data['widgets'][name]
    p, slot = w['properties'], w['slot']
    brush = p.get('Brush', {})
    layout = slot.get('LayoutData', {})
    offsets = layout.get('Offsets', {})
    assert p.get('RenderTransformPivot', {'X': .5, 'Y': .5}) == {'X': .5, 'Y': .5}
    if index >= 2:
        assert layout['Anchors']['Minimum'] == {'X': .5, 'Y': .5}
        assert layout['Alignment'] == {'X': .5, 'Y': .5}
    values = dict(Opacity=p.get('RenderOpacity', 1), Alpha=p.get('ColorAndOpacity', {}).get('A', 1),
                  Visibility=1 if p.get('Visibility') == 'ESlateVisibility::Collapsed' else 0,
                  ScaleX=1, ScaleY=1, X=0, Y=0, Angle=0,
                  Width=offsets.get('Right', 0), Height=offsets.get('Bottom', 0))
    values.update(X=offsets.get('Left', 0), Y=offsets.get('Top', 0))
    if slot.get('bAutoSize'):
        values.update(Width=brush['ImageSize']['X'], Height=brush['ImageSize']['Y'])
    expressions = {k: num(v) for k, v in values.items()}
    for track in data['tracks']:
        target = track['widget'].replace('WidgetSwitcher_Icon', 'Image_FeedbackIcon')
        if target != name:
            continue
        prop, curves = track['property'], track['curves']
        mapping = {'RenderOpacity': [('Opacity', 'FloatCurve')],
                   'ColorAndOpacity': [('Alpha', 'AlphaCurve')],
                   'Visibility': [('Visibility', 'ByteCurve')],
                   'LayoutData.Offsets': [('X', 'LeftCurve'), ('Y', 'TopCurve'), ('Width', 'RightCurve'), ('Height', 'BottomCurve')]}.get(prop, [])
        if prop == 'RenderTransform':
            mapping = [(field, key) for bit, field, key in [(1, 'X', 'Translation'), (2, 'Y', 'Translation[1]'),
                       (4, 'Angle', 'Rotation'), (8, 'ScaleX', 'Scale'), (16, 'ScaleY', 'Scale[1]')]
                       if (track['mask'] or 127) & bit]
        for field, key in mapping:
            c = curves.get(key)
            if not c:
                continue
            if not c['Times']:
                if c['bHasDefaultValue']:
                    expressions[field] = num(c['DefaultValue'])
                continue
            curve_name = f'C{len(fields)}'
            keys = []
            for t, v in zip(c['Times'], c['Values']):
                if not isinstance(v, dict):
                    v = {'Value': v, 'InterpMode': 1}
                tangent = v.get('Tangent', {})
                keys.append('new Key(' + ', '.join(num(x) for x in [t['Value'], v['Value'], tangent.get('ArriveTangent', 0), tangent.get('LeaveTangent', 0)]) + f", {v['InterpMode']})")
            fields.append(f'        private static readonly Key[] {curve_name} = {{ ' + ', '.join(keys) + ' };')
            expressions[field] = f'Sample({curve_name}, seconds)'
    texture = brush.get('ResourceObject', {}).get('ObjectPath', '').split('/')[-1].replace('SPR_UI_HUDPC_', '')
    nine = brush.get('DrawAs') == 'ESlateBrushDrawType::Box'
    if nine:
        assert all(v == .5 for v in brush['Margin'].values())
    assignments = ', '.join(k + ' = ' + v for k, v in expressions.items())
    methods.append(f'                case {index}: return new Layer {{ Name = "{name}", Texture = "{texture}", NineSlice = {str(nine).lower()}, {assignments} }};')

output = '''// Generated by SourceAssets/GameStyles/calabiyau/build_motion.py; do not hand-edit.
// Anim_Normal, WBP_IconFeedbackPage, game build 832047. Legacy WidgetSwitcher_Icon
// tracks are explicitly mapped to Image_FeedbackIcon; particles/materials are excluded.
using System;
namespace KillConfirmCompatibility.Contracts
{
    public static class CalabiyauMotion
    {
        public const double Duration = 3.5;
        public const int LayerCount = 10;
        public struct Layer
        {
            public string Name, Texture;
            public bool NineSlice;
            public double Opacity, Alpha, Visibility, ScaleX, ScaleY, X, Y, Angle, Width, Height;
            public bool Visible => Visibility != 1 && Visibility != 2;
        }
        private struct Key
        {
            public double Tick, Value, Arrive, Leave;
            public int Mode;
            public Key(double tick, double value, double arrive, double leave, int mode)
            { Tick = tick; Value = value; Arrive = arrive; Leave = leave; Mode = mode; }
        }
        private static double Sample(Key[] keys, double seconds)
        {
            double tick = seconds * 60000;
            if (tick <= keys[0].Tick) return keys[0].Value;
            if (tick >= keys[keys.Length - 1].Tick) return keys[keys.Length - 1].Value;
            int i = 0;
            while (keys[i + 1].Tick <= tick) i++;
            Key a = keys[i], b = keys[i + 1];
            double dt = b.Tick - a.Tick, u = (tick - a.Tick) / dt;
            if (a.Mode == 1) return a.Value;
            if (a.Mode != 2) return a.Value + (b.Value - a.Value) * u;
            return (2*u*u*u - 3*u*u + 1)*a.Value + (u*u*u - 2*u*u + u)*a.Leave*dt
                + (-2*u*u*u + 3*u*u)*b.Value + (u*u*u - u*u)*b.Arrive*dt;
        }
'''
output += '\n'.join(fields) + '''
        public static Layer At(int layer, double seconds)
        {
            switch (layer)
            {
''' + '\n'.join(methods) + '''
                default: throw new ArgumentOutOfRangeException(nameof(layer));
            }
        }
    }
}
'''
(ROOT / 'Common/CalabiyauMotion.cs').write_text(output, encoding='utf-8')
print(f'Generated {len(fields)} curves, {len(names)} layers')
